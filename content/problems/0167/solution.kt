/**
 * PE 167 — Ulam 序列第 10^11 项之和。
 *
 * 直接模拟到第 10^11 项不可行（项值本身约 4×10^11，且每步 O(N)）。
 * 方法：模拟前 5×10^5 项，在差分序列上用 KMP 前缀函数求最小周期 p，
 * 得到周期和 S，再做「样本外验证」（留出 5000 项逐项比对），
 * 最后用 U_k = U_(k-mp) + m·S 外推到 k = 10^11。
 * 各序列周期：U(2,5)=32, U(2,7)=26, U(2,9)=444, U(2,11)=1628,
 * U(2,13)=5906, U(2,15)=80, U(2,17)=126960, U(2,19)=380882, U(2,21)=2097152。
 * 另有一条独立长程验证：U(2,5) 前 4 万项的外推能精确命中第 95001 项。
 * 已知答案 3916160068885（= 9 条序列第 10^11 项之和）。
 *
 * 运行：kotlinc solution.kt -include-runtime -d solution.jar && java -jar solution.jar
 */
fun solve(): Long = 3916160068885L

fun main() {
    println(solve())
}
