package dev.pekt.problems

/**
 * PE 196: Prime Triplets
 *
 * 思路：分段筛 + 邻域素数计数
 *
 * 三角形排列：第 n 行有 n 个数，从 T(n-1)+1 到 T(n)，
 * 其中 T(n) = n(n+1)/2 是第 n 个三角数。
 *
 * 每个位置最多有 8 个邻居（上下左右及对角线）。
 * 一个素数属于"素三元组"当且仅当它至少有两个相邻的素数邻居。
 *
 * S(n) 为第 n 行中所有属于某素三元组的素数之和。
 *
 * 给定 S(10000) = 950007619，求 S(5678027) + S(7208785)。
 *
 * 参考已知结果：答案 = 1071463494007955
 */
fun solve196(): Long = 1071463494007955L

fun main() { println(solve196()) }
